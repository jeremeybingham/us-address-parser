//! Compiles `data/*.toml` and the enabled state packs (`data/packs/<st>/`,
//! feature `state-<st>`) into static, sorted lookup tables
//! (`$OUT_DIR/lexicon_tables.rs`, included by `src/lexicon.rs`).
//!
//! Doing this at build time keeps `addr-core` free of runtime dependencies
//! and of any runtime data loading, and turns a malformed or contradictory
//! table into a build error instead of a parse-time surprise.
//!
//! The data lives at the workspace root (`../../data`). Publishing to
//! crates.io will need the tables inside the package; that is handled in the
//! release milestone. A `data/` directory inside the crate wins if present.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

use toml::{Table, Value};

#[path = "src/lexicon/key.rs"]
mod key;
use key::normalize_key;

#[path = "src/lexicon/place_key.rs"]
mod place_key;
use place_key::place_key;

/// Word -> full name, for the place comparison key: every suffix and
/// directional spelling mapped to its full name (`SPGS` -> `SPRINGS`).
type Expand = BTreeMap<String, String>;

type Result<T> = std::result::Result<T, String>;

fn main() {
    if let Err(e) = run() {
        eprintln!("error: addr-core lexicon build failed: {e}");
        std::process::exit(1);
    }
}

fn data_dir() -> Result<PathBuf> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").map_err(|e| e.to_string())?);
    for dir in [manifest.join("data"), manifest.join("../../data")] {
        if dir.join("suffixes.toml").is_file() {
            return Ok(dir);
        }
    }
    Err(format!(
        "no data/ directory found near {}",
        manifest.display()
    ))
}

fn run() -> Result<()> {
    let dir = data_dir()?;
    println!("cargo:rerun-if-changed=src/lexicon/key.rs");
    println!("cargo:rerun-if-changed=src/lexicon/place_key.rs");
    let mut out = String::from("// @generated by build.rs from data/. Do not edit.\n\n");
    let mut max_words = 1;
    let mut expand = Expand::new();

    gen_suffixes(
        &load(&dir, "suffixes.toml")?,
        &mut out,
        &mut max_words,
        &mut expand,
    )?;
    gen_directionals(
        &load(&dir, "directionals.toml")?,
        &mut out,
        &mut max_words,
        &mut expand,
    )?;
    gen_units(&load(&dir, "units.toml")?, &mut out, &mut max_words)?;
    gen_states(&load(&dir, "states.toml")?, &mut out, &mut max_words)?;
    gen_special(&load(&dir, "special.toml")?, &mut out, &mut max_words)?;
    gen_packs(&dir.join("packs"), &expand, &mut out)?;

    writeln!(
        out,
        "/// Most words in any multi-word form across all tables."
    )
    .ok();
    writeln!(out, "pub const MAX_FORM_WORDS: usize = {max_words};").ok();

    let dest =
        PathBuf::from(env::var("OUT_DIR").map_err(|e| e.to_string())?).join("lexicon_tables.rs");
    fs::write(&dest, out).map_err(|e| format!("{}: {e}", dest.display()))
}

fn load(dir: &Path, name: &str) -> Result<Table> {
    let path = dir.join(name);
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    text.parse::<Table>().map_err(|e| format!("{name}: {e}"))
}

// ---- TOML access helpers -------------------------------------------------

fn array<'a>(t: &'a Table, key: &str, ctx: &str) -> Result<&'a [Value]> {
    match t.get(key) {
        Some(Value::Array(a)) => Ok(a),
        Some(_) => Err(format!("{ctx}: `{key}` must be an array")),
        None => Err(format!("{ctx}: missing `{key}`")),
    }
}

fn tables<'a>(t: &'a Table, key: &str, ctx: &str) -> Result<Vec<&'a Table>> {
    array(t, key, ctx)?
        .iter()
        .map(|v| {
            v.as_table()
                .ok_or_else(|| format!("{ctx}: `{key}` entries must be tables"))
        })
        .collect()
}

fn table<'a>(t: &'a Table, key: &str, ctx: &str) -> Result<&'a Table> {
    t.get(key)
        .and_then(Value::as_table)
        .ok_or_else(|| format!("{ctx}: missing table `[{key}]`"))
}

/// A string field that must already be a normalized lexicon key.
fn key_str(t: &Table, key: &str, ctx: &str) -> Result<String> {
    let s = t
        .get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| format!("{ctx}: missing string `{key}`"))?;
    check_key(s, ctx)?;
    Ok(s.to_string())
}

fn key_list(t: &Table, key: &str, ctx: &str, required: bool) -> Result<Vec<String>> {
    let Some(v) = t.get(key) else {
        return if required {
            Err(format!("{ctx}: missing `{key}`"))
        } else {
            Ok(Vec::new())
        };
    };
    let a = v
        .as_array()
        .ok_or_else(|| format!("{ctx}: `{key}` must be an array"))?;
    let mut out = Vec::new();
    for item in a {
        let s = item
            .as_str()
            .ok_or_else(|| format!("{ctx}: `{key}` must hold strings"))?;
        check_key(s, ctx)?;
        if out.iter().any(|o: &String| o == s) {
            return Err(format!("{ctx}: `{s}` listed twice in `{key}`"));
        }
        out.push(s.to_string());
    }
    if required && out.is_empty() {
        return Err(format!("{ctx}: `{key}` is empty"));
    }
    Ok(out)
}

fn check_key(s: &str, ctx: &str) -> Result<()> {
    if s.is_empty() || normalize_key(s) != s {
        return Err(format!(
            "{ctx}: `{s}` is not a normalized key (expected `{}`)",
            normalize_key(s)
        ));
    }
    Ok(())
}

fn words(s: &str) -> usize {
    s.split(' ').count()
}

/// Sorted index of (key, payload). Rejects a key that maps to two payloads.
#[derive(Default)]
struct Index(BTreeMap<String, String>);

impl Index {
    fn add(&mut self, key: &str, payload: String, ctx: &str, max_words: &mut usize) -> Result<()> {
        *max_words = (*max_words).max(words(key));
        if let Some(prev) = self.0.insert(key.to_string(), payload.clone()) {
            if prev != payload {
                return Err(format!("{ctx}: `{key}` maps to both {prev} and {payload}"));
            }
        }
        Ok(())
    }

    fn emit(&self, out: &mut String, name: &str, ty: &str) {
        writeln!(out, "pub(crate) static {name}: &[(&str, {ty})] = &[").ok();
        for (k, v) in &self.0 {
            writeln!(out, "    ({k:?}, {v}),").ok();
        }
        writeln!(out, "];\n").ok();
    }
}

/// Classify a form against its entry's standard abbreviation and full name.
fn kind(form: &str, abbr: &str, name: &str) -> &'static str {
    if form == abbr {
        "MatchKind::Standard"
    } else if form == name {
        "MatchKind::FullName"
    } else {
        "MatchKind::Variant"
    }
}

// ---- tables --------------------------------------------------------------

fn gen_suffixes(t: &Table, out: &mut String, mw: &mut usize, ex: &mut Expand) -> Result<()> {
    let rows = tables(t, "suffix", "suffixes.toml")?;
    let mut index = Index::default();
    writeln!(out, "pub(crate) static SUFFIXES: &[SuffixRow] = &[").ok();
    let mut abbrs = Vec::new();
    for (i, r) in rows.iter().enumerate() {
        let ctx = format!("suffixes.toml [[suffix]] #{}", i + 1);
        let (name, abbr) = (key_str(r, "name", &ctx)?, key_str(r, "abbr", &ctx)?);
        let forms = key_list(r, "forms", &ctx, true)?;
        let observed = key_list(r, "observed", &ctx, false)?;
        if !forms.contains(&abbr) || !forms.contains(&name) {
            return Err(format!(
                "{ctx}: forms must include name `{name}` and abbr `{abbr}`"
            ));
        }
        if abbrs.contains(&abbr) {
            return Err(format!("{ctx}: abbreviation `{abbr}` used by two entries"));
        }
        abbrs.push(abbr.clone());
        writeln!(out, "    SuffixRow {{ name: {name:?}, abbr: {abbr:?} }},").ok();
        for f in &forms {
            index.add(f, format!("({i}, {})", kind(f, &abbr, &name)), &ctx, mw)?;
        }
        for f in &observed {
            index.add(f, format!("({i}, MatchKind::Observed)"), &ctx, mw)?;
        }
        for f in forms.iter().chain(&observed) {
            ex.insert(f.clone(), name.clone());
        }
    }
    writeln!(out, "];\n").ok();
    index.emit(out, "SUFFIX_INDEX", "(u16, MatchKind)");
    Ok(())
}

fn gen_directionals(t: &Table, out: &mut String, mw: &mut usize, ex: &mut Expand) -> Result<()> {
    let rows = tables(t, "directional", "directionals.toml")?;
    let mut index = Index::default();
    let mut seen = Vec::new();
    for (i, r) in rows.iter().enumerate() {
        let ctx = format!("directionals.toml [[directional]] #{}", i + 1);
        let (name, abbr) = (key_str(r, "name", &ctx)?, key_str(r, "abbr", &ctx)?);
        // The abbreviation names a variant of the `Directional` enum.
        if !matches!(
            abbr.as_str(),
            "N" | "S" | "E" | "W" | "NE" | "NW" | "SE" | "SW"
        ) {
            return Err(format!("{ctx}: `{abbr}` is not a Directional variant"));
        }
        if seen.contains(&abbr) {
            return Err(format!("{ctx}: `{abbr}` listed twice"));
        }
        seen.push(abbr.clone());
        let forms = key_list(r, "forms", &ctx, true)?;
        if !forms.contains(&abbr) || !forms.contains(&name) {
            return Err(format!(
                "{ctx}: forms must include name `{name}` and abbr `{abbr}`"
            ));
        }
        for f in &forms {
            let payload = format!("(Directional::{abbr}, {})", kind(f, &abbr, &name));
            index.add(f, payload, &ctx, mw)?;
            // Directionals win over suffixes for a word that is both.
            ex.insert(f.clone(), name.clone());
        }
    }
    if seen.len() != 8 {
        return Err("directionals.toml: expected all 8 directionals".into());
    }
    index.emit(out, "DIRECTIONAL_INDEX", "(Directional, MatchKind)");
    Ok(())
}

fn gen_units(t: &Table, out: &mut String, mw: &mut usize) -> Result<()> {
    let rows = tables(t, "unit", "units.toml")?;
    let mut index = Index::default();
    let mut abbrs = Vec::new();
    writeln!(out, "pub(crate) static UNITS: &[UnitRow] = &[").ok();
    for (i, r) in rows.iter().enumerate() {
        let ctx = format!("units.toml [[unit]] #{}", i + 1);
        let (name, abbr) = (key_str(r, "name", &ctx)?, key_str(r, "abbr", &ctx)?);
        let range = r
            .get("range_required")
            .and_then(Value::as_bool)
            .ok_or_else(|| format!("{ctx}: missing bool `range_required`"))?;
        let forms = key_list(r, "forms", &ctx, true)?;
        let observed = key_list(r, "observed", &ctx, false)?;
        if !forms.contains(&abbr) || !forms.contains(&name) {
            return Err(format!(
                "{ctx}: forms must include name `{name}` and abbr `{abbr}`"
            ));
        }
        if abbrs.contains(&abbr) {
            return Err(format!("{ctx}: abbreviation `{abbr}` used by two entries"));
        }
        abbrs.push(abbr.clone());
        writeln!(
            out,
            "    UnitRow {{ name: {name:?}, abbr: {abbr:?}, range_required: {range} }},"
        )
        .ok();
        for f in &forms {
            index.add(f, format!("({i}, {})", kind(f, &abbr, &name)), &ctx, mw)?;
        }
        for f in &observed {
            index.add(f, format!("({i}, MatchKind::Observed)"), &ctx, mw)?;
        }
    }
    writeln!(out, "];\n").ok();
    index.emit(out, "UNIT_INDEX", "(u16, MatchKind)");
    Ok(())
}

fn gen_states(t: &Table, out: &mut String, mw: &mut usize) -> Result<()> {
    let rows = tables(t, "state", "states.toml")?;
    let mut index = Index::default();
    let mut codes = Vec::new();
    writeln!(out, "pub(crate) static STATES: &[StateRow] = &[").ok();
    for (i, r) in rows.iter().enumerate() {
        let ctx = format!("states.toml [[state]] #{}", i + 1);
        let (code, name) = (key_str(r, "code", &ctx)?, key_str(r, "name", &ctx)?);
        if code.len() != 2 || !code.bytes().all(|b| b.is_ascii_uppercase()) {
            return Err(format!("{ctx}: code `{code}` must be two letters"));
        }
        if codes.contains(&code) {
            return Err(format!("{ctx}: code `{code}` listed twice"));
        }
        codes.push(code.clone());
        let kind = match r.get("kind").and_then(Value::as_str) {
            Some("state") => "State",
            Some("district") => "District",
            Some("territory") => "Territory",
            Some("freely_associated") => "FreelyAssociated",
            Some("military") => "Military",
            other => return Err(format!("{ctx}: bad kind {other:?}")),
        };
        writeln!(
            out,
            "    StateRow {{ code: {code:?}, name: {name:?}, kind: StateKind::{kind} }},"
        )
        .ok();
        index.add(&code, format!("({i}, MatchKind::Standard)"), &ctx, mw)?;
        index.add(&name, format!("({i}, MatchKind::FullName)"), &ctx, mw)?;
        for a in key_list(r, "aliases", &ctx, false)? {
            index.add(&a, format!("({i}, MatchKind::Variant)"), &ctx, mw)?;
        }
    }
    writeln!(out, "];\n").ok();
    index.emit(out, "STATE_INDEX", "(u16, MatchKind)");
    Ok(())
}

fn gen_special(t: &Table, out: &mut String, mw: &mut usize) -> Result<()> {
    let ctx = "special.toml";
    let mut index = Index::default();
    for (key, variant) in [
        ("po_box", "PoBox"),
        ("box", "Box"),
        ("rural_route", "RuralRoute"),
        ("highway_contract", "HighwayContract"),
        ("general_delivery", "GeneralDelivery"),
        ("attention", "Attention"),
    ] {
        let tctx = format!("{ctx} [{key}]");
        let tb = table(t, key, ctx)?;
        let standard = key_str(tb, "standard", &tctx)?;
        let forms = key_list(tb, "forms", &tctx, true)?;
        if !forms.contains(&standard) {
            return Err(format!("{tctx}: forms must include `{standard}`"));
        }
        for f in &forms {
            let k = if *f == standard {
                "Standard"
            } else {
                "Variant"
            };
            index.add(
                f,
                format!("(Special::{variant}, MatchKind::{k})"),
                &tctx,
                mw,
            )?;
        }
        for f in key_list(tb, "synonyms", &tctx, false)? {
            index.add(
                &f,
                format!("(Special::{variant}, MatchKind::Variant)"),
                &tctx,
                mw,
            )?;
        }
    }
    index.emit(out, "SPECIAL_INDEX", "(Special, MatchKind)");

    let mut hw = Index::default();
    let mut standards = Vec::new();
    for (i, r) in tables(t, "highway", ctx)?.iter().enumerate() {
        let hctx = format!("{ctx} [[highway]] #{}", i + 1);
        let standard = key_str(r, "standard", &hctx)?;
        let forms = key_list(r, "forms", &hctx, true)?;
        if !forms.contains(&standard) {
            return Err(format!("{hctx}: forms must include `{standard}`"));
        }
        standards.push(standard.clone());
        for f in &forms {
            let k = if *f == standard {
                "Standard"
            } else {
                "Variant"
            };
            hw.add(f, format!("({i}, MatchKind::{k})"), &hctx, mw)?;
        }
        for f in key_list(r, "observed", &hctx, false)? {
            hw.add(&f, format!("({i}, MatchKind::Observed)"), &hctx, mw)?;
        }
    }
    writeln!(
        out,
        "pub(crate) static HIGHWAYS: &[&str] = &{standards:?};\n"
    )
    .ok();
    hw.emit(out, "HIGHWAY_INDEX", "(u16, MatchKind)");

    gen_fixed(
        t,
        "military",
        "MilitaryKind",
        &[
            ("CPR", "Cpr"),
            ("OPC", "Opc"),
            ("PSC", "Psc"),
            ("UPR", "Upr"),
            ("UNIT", "Unit"),
        ],
        "MILITARY_INDEX",
        out,
        mw,
    )?;
    gen_fixed(
        t,
        "military_post_office",
        "MilitaryPostOffice",
        &[("APO", "Apo"), ("FPO", "Fpo"), ("DPO", "Dpo")],
        "MILITARY_PO_INDEX",
        out,
        mw,
    )?;

    let pctx = format!("{ctx} [placeholder]");
    let mut phrases = key_list(table(t, "placeholder", ctx)?, "phrases", &pctx, true)?;
    phrases.sort();
    writeln!(
        out,
        "pub(crate) static PLACEHOLDERS: &[&str] = &{phrases:?};\n"
    )
    .ok();

    let bctx = format!("{ctx} [building]");
    let mut words = key_list(table(t, "building", ctx)?, "words", &bctx, true)?;
    words.sort();
    writeln!(
        out,
        "pub(crate) static BUILDING_WORDS: &[&str] = &{words:?};\n"
    )
    .ok();
    Ok(())
}

/// An `[[array]]` of `standard` + `forms` entries whose standards form a
/// fixed set, each mapped to an enum variant. Unknown or missing standards
/// are build errors.
#[allow(clippy::too_many_arguments)]
fn gen_fixed(
    t: &Table,
    key: &str,
    ty: &str,
    variants: &[(&str, &str)],
    index_name: &str,
    out: &mut String,
    mw: &mut usize,
) -> Result<()> {
    let ctx = format!("special.toml [[{key}]]");
    let mut index = Index::default();
    let mut seen = Vec::new();
    for (i, r) in tables(t, key, &ctx)?.iter().enumerate() {
        let ectx = format!("{ctx} #{}", i + 1);
        let standard = key_str(r, "standard", &ectx)?;
        let variant = variants
            .iter()
            .find(|(s, _)| *s == standard)
            .map(|(_, v)| *v)
            .ok_or_else(|| format!("{ectx}: unknown standard `{standard}`"))?;
        let forms = key_list(r, "forms", &ectx, true)?;
        if !forms.contains(&standard) {
            return Err(format!("{ectx}: forms must include `{standard}`"));
        }
        seen.push(standard.clone());
        for f in &forms {
            let k = if *f == standard {
                "Standard"
            } else {
                "Variant"
            };
            index.add(f, format!("({ty}::{variant}, MatchKind::{k})"), &ectx, mw)?;
        }
    }
    for (s, _) in variants {
        if !seen.iter().any(|x| x == s) {
            return Err(format!("{ctx}: missing entry for `{s}`"));
        }
    }
    index.emit(out, index_name, &format!("({ty}, MatchKind)"));
    Ok(())
}

