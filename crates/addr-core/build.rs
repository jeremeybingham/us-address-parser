/// Rows of a pack `.tsv` file: a header naming `cols`, then tab-separated
/// rows with exactly that many fields.
fn tsv(path: &Path, cols: &[&str]) -> Result<Vec<Vec<String>>> {
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut lines = text.lines();
    let header: Vec<&str> = lines.next().unwrap_or("").split('\t').collect();
    if header != cols {
        return Err(format!("{}: header must be {cols:?}", path.display()));
    }
    let mut rows = Vec::new();
    for (n, line) in lines.enumerate() {
        let row: Vec<String> = line.split('\t').map(str::to_string).collect();
        if row.len() != cols.len() {
            return Err(format!(
                "{}:{}: expected {} fields",
                path.display(),
                n + 2,
                cols.len()
            ));
        }
        rows.push(row);
    }
    Ok(rows)
}

fn list(s: &str) -> Vec<&str> {
    s.split(';').filter(|v| !v.is_empty()).collect()
}

/// The state packs enabled by `state-<st>` features, in state order. Each
/// adds places and ZIPs; nothing in a pack replaces another entry, and a
/// spelling or ZIP that would lead to two places is a build error.
fn gen_packs(dir: &Path, ex: &Expand, out: &mut String) -> Result<()> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut states = Vec::new();
    if let Ok(entries) = fs::read_dir(dir) {
        for e in entries.flatten() {
            let st = e.file_name().to_string_lossy().to_uppercase();
            if env::var_os(format!("CARGO_FEATURE_STATE_{st}")).is_some() {
                states.push(st);
            }
        }
    }
    states.sort();

    let expand = |w: &str| ex.get(w).cloned();
    let mut rows = Vec::new(); // PlaceRow literals
    let mut index: BTreeMap<String, (usize, &str)> = BTreeMap::new();
    let mut zips: BTreeMap<String, (usize, Vec<usize>)> = BTreeMap::new();
    let mut max_words = 1;
    for st in &states {
        let pdir = dir.join(st.to_lowercase());
        let meta = load(&pdir, "pack.toml")?;
        let ctx = format!("packs/{} pack.toml", st.to_lowercase());
        if key_str(&meta, "state", &ctx)? != *st {
            return Err(format!("{ctx}: `state` must be {st}"));
        }
        let places = tsv(
            &pdir.join("places.tsv"),
            &["name", "county", "kind", "sources", "variants"],
        )?;
        let first = rows.len();
        let mut by_name = BTreeMap::new();
        // Names first, so a variant that the comparison rule already covers
        // is dropped rather than reported as a clash.
        for r in &places {
            let (name, county, kind) = (&r[0], &r[1], &r[2]);
            let ctx = format!("packs/{} places.tsv {name}", st.to_lowercase());
            check_key(name, &ctx)?;
            let kind = match kind.as_str() {
                "municipality" => "Municipality",
                "place" => "Place",
                k => return Err(format!("{ctx}: bad kind `{k}`")),
            };
            let i = rows.len();
            rows.push(format!(
                "PlaceRow {{ state: {st:?}, name: {name:?}, county: {county:?}, kind: PlaceKind::{kind} }}"
            ));
            by_name.insert(name.clone(), i);
            max_words = max_words.max(words(name));
            let key = format!("{st}|{}", place_key(name, expand));
            if let Some((j, _)) = index.insert(key.clone(), (i, "Standard")) {
                return Err(format!("{ctx}: same key `{key}` as row {j}"));
            }
        }
        for r in &places {
            let (name, i) = (&r[0], by_name[&r[0]]);
            let ctx = format!("packs/{} places.tsv {name}", st.to_lowercase());
            for v in list(&r[4]) {
                check_key(v, &ctx)?;
                let key = format!("{st}|{}", place_key(v, expand));
                match index.get(&key) {
                    Some((j, _)) if *j == i => {}
                    Some((j, _)) => {
                        return Err(format!("{ctx}: variant `{v}` also leads to row {j}"));
                    }
                    None => {
                        index.insert(key, (i, "Variant"));
                        max_words = max_words.max(words(v));
                    }
                }
            }
        }
        let place = |n: &str, ctx: &str| {
            by_name
                .get(n)
                .copied()
                .ok_or_else(|| format!("{ctx}: unknown place `{n}`"))
        };
        for r in tsv(&pdir.join("zips.tsv"), &["zip", "place", "shared"])? {
            let ctx = format!("packs/{} zips.tsv {}", st.to_lowercase(), r[0]);
            if r[0].len() != 5 || !r[0].bytes().all(|b| b.is_ascii_digit()) {
                return Err(format!("{ctx}: not a 5-digit ZIP"));
            }
            let main = place(&r[1], &ctx)?;
            let shared = list(&r[2])
                .into_iter()
                .map(|n| place(n, &ctx))
                .collect::<Result<Vec<_>>>()?;
            if shared.contains(&main) {
                return Err(format!("{ctx}: main place also listed as shared"));
            }
            if zips.insert(r[0].clone(), (main, shared)).is_some() {
                return Err(format!("{ctx}: ZIP listed twice"));
            }
        }
        if rows.len() == first {
            return Err(format!("packs/{}: no places", st.to_lowercase()));
        }
    }

    writeln!(out, "/// State packs compiled in.").ok();
    writeln!(
        out,
        "pub(crate) static PACK_STATES: &[&str] = &{states:?};\n"
    )
    .ok();
    writeln!(out, "pub(crate) static PLACES: &[PlaceRow] = &[").ok();
    for r in &rows {
        writeln!(out, "    {r},").ok();
    }
    writeln!(out, "];\n").ok();
    writeln!(
        out,
        "/// `STATE|key` (see `place_key`) -> place row and how it is spelled."
    )
    .ok();
    writeln!(
        out,
        "pub(crate) static PLACE_INDEX: &[(&str, (u32, MatchKind))] = &["
    )
    .ok();
    for (k, (i, kind)) in &index {
        writeln!(out, "    ({k:?}, ({i}, MatchKind::{kind})),").ok();
    }
    writeln!(out, "];\n").ok();
    writeln!(out, "/// ZIP -> main place row and shared place rows.").ok();
    writeln!(
        out,
        "pub(crate) static ZIP_INDEX: &[(&str, (u32, &[u32]))] = &["
    )
    .ok();
    for (z, (main, shared)) in &zips {
        writeln!(out, "    ({z:?}, ({main}, &{shared:?})),").ok();
    }
    writeln!(out, "];\n").ok();
    writeln!(out, "/// Most words in any place name or variant.").ok();
    writeln!(out, "pub const MAX_PLACE_WORDS: usize = {max_words};").ok();
    Ok(())
}
