"""Write tests/external/usaddress/in_training.txt: the addresses in the
vendored usaddress test files that also appear in usaddress's training files
at the pinned commit. compare_usaddress.py scores those apart, since
usaddress has seen them.

    python tools/compare/training_overlap.py

Downloads the training files (about 8 MB) into memory; nothing is kept.
"""
import html
import os
import re
import sys
import urllib.request

COMMIT = "aa7699b53a0843fc443f9e87285b88cbd9eaf50a"
TRAINING = [
    "labeled.xml",
    "multi_word_state_addresses.xml",
    "synthetic_clean_osm_data.xml",
    "synthetic_osm_data_xml.xml",
    "us50_messiest_manual_label.xml",
    "us50_train_tagged.xml",
    "example_training.xml",
    "openaddress_us_ia_linn.xml",
]
HERE = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "external", "usaddress")


def key(s):
    """The comparison form: whitespace collapsed, lowercase."""
    return " ".join(s.split()).lower()


def strings(text):
    # A regex, not an XML parser: one training file is not well-formed.
    for m in re.finditer(r"<AddressString>(.*?)</AddressString>", text, re.S):
        yield key(html.unescape(re.sub(r"<[^>]+>", "", m.group(1))))


def main():
    seen = set()
    for name in TRAINING:
        url = f"https://raw.githubusercontent.com/datamade/usaddress/{COMMIT}/training/{name}"
        print(f"fetching {name}", file=sys.stderr)
        with urllib.request.urlopen(url, timeout=120) as r:  # noqa: S310 (fixed https URL)
            seen.update(strings(r.read().decode("utf-8", errors="replace")))
    overlap = set()
    for name in sorted(os.listdir(HERE)):
        if name.endswith(".xml"):
            with open(os.path.join(HERE, name), encoding="utf-8") as fh:
                overlap.update(s for s in strings(fh.read()) if s in seen)
    out = os.path.join(HERE, "in_training.txt")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(f"# Test addresses also in usaddress's training data at {COMMIT}.\n")
        fh.write("# Generated by tools/compare/training_overlap.py; one per line, whitespace\n")
        fh.write("# collapsed and lowercased.\n")
        for s in sorted(overlap):
            fh.write(s + "\n")
    print(f"wrote {len(overlap)} addresses to {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
